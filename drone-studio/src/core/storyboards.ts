import { z } from 'zod';
import { projectSchema, type Project } from './model';

/** This library is separate from the existing current-project autosave. */
export const STORYBOARDS_STORAGE_KEY = 'lucidity.studio.storyboards.v1';

export type StoredStoryboard = { project: Project; updatedAt: number; deletedAt?: number };

const timestampSchema = z.number().finite().nonnegative();
const librarySchema = z
  .array(
    z
      .object({
        project: projectSchema,
        updatedAt: timestampSchema,
        deletedAt: timestampSchema.optional(),
      })
      .strict()
  )
  .superRefine((entries, context) => {
    if (new Set(entries.map((entry) => entry.project.id)).size !== entries.length)
      context.addIssue({ code: 'custom', message: 'Storyboard IDs must be unique.' });
  });

/** Read active and deleted documents together so every mutation preserves both. */
function loadLibrary(storage: Pick<Storage, 'getItem'>): StoredStoryboard[] | undefined {
  let raw: string | null;
  try {
    raw = storage.getItem(STORYBOARDS_STORAGE_KEY);
  } catch (cause) {
    throw new Error('Could not read the storyboard library from local storage.', { cause });
  }
  if (raw === null) return undefined;
  try {
    const entries = structuredClone(librarySchema.parse(JSON.parse(raw)));
    // Rename only the untouched name/scene generated by the former guided template.
    // Preserve IDs, revisions, edits, and deleted entries; the next normal save persists it.
    for (const entry of entries) {
      if (entry.project.name === 'Zorro kill-switch test' &&
        entry.project.cues.some(scene => scene.metadata?.operatorTest === 'zorro-estop-props-off-v1')) {
        entry.project.name = 'Props-off idle';
        if (entry.project.cues[0]?.name === 'All-four motor stop') entry.project.cues[0].name = 'Armed idle';
      }
    }
    return entries;
  } catch (cause) {
    throw new Error(
      'The storyboard library is malformed. Stored storyboards were left unchanged.',
      {
        cause,
      }
    );
  }
}

export function loadStoryboards(storage: Pick<Storage, 'getItem'>): StoredStoryboard[] {
  return (loadLibrary(storage) ?? []).filter((entry) => entry.deletedAt === undefined);
}

export function loadDeletedStoryboards(storage: Pick<Storage, 'getItem'>): StoredStoryboard[] {
  return (loadLibrary(storage) ?? []).filter((entry) => entry.deletedAt !== undefined);
}

export function isStoryboardDeleted(storage: Pick<Storage, 'getItem'>, id: string): boolean {
  return (loadLibrary(storage) ?? []).some(
    (entry) => entry.project.id === id && entry.deletedAt !== undefined
  );
}

/** An intentionally empty library should not acquire a fallback draft on startup. */
export function shouldPersistInitialStoryboard(
  storage: Pick<Storage, 'getItem'>,
  legacyKey: string
): boolean {
  try {
    const library = loadLibrary(storage);
    if (!library || library.some((entry) => entry.deletedAt === undefined)) return true;
    const raw = storage.getItem(legacyKey);
    if (raw === null) return false;
    let legacy: Project;
    try {
      legacy = projectSchema.parse(JSON.parse(raw));
    } catch {
      return false;
    }
    return !library.some((entry) => entry.project.id === legacy.id);
  } catch {
    // Preserve the existing startup path, which surfaces read/save failures.
    return true;
  }
}

/**
 * Recover a document without writing during startup. The library is saved before
 * the legacy current-project key, so an equal or newer matching library revision
 * wins if that second write was interrupted. Ordinary library operations still
 * surface corruption/read errors rather than silently replacing stored data.
 */
export function resolveInitialStoryboard(
  storage: Pick<Storage, 'getItem'>,
  legacyKey: string,
  fallback: Project
): Project {
  let legacy: Project | undefined;
  let library: StoredStoryboard[] = [];
  try {
    const raw = storage.getItem(legacyKey);
    if (raw !== null) legacy = projectSchema.parse(JSON.parse(raw));
  } catch {
    // A valid library may still recover work if the legacy autosave is unavailable.
  }
  try {
    const entries = loadLibrary(storage) ?? [];
    if (
      entries.some((entry) => entry.project.id === legacy?.id && entry.deletedAt !== undefined)
    )
      legacy = undefined;
    library = entries.filter((entry) => entry.deletedAt === undefined);
  } catch {
    // Keep a valid legacy document; the later save reports this library failure.
  }
  if (legacy) {
    const legacyId = legacy.id;
    const matching = library.find((entry) => entry.project.id === legacyId);
    if (matching && matching.project.name === 'Props-off idle' && legacy.name === 'Zorro kill-switch test')
      legacy = matching.project;
    return structuredClone(
      matching && matching.project.revision >= legacy.revision ? matching.project : legacy
    );
  }
  const recent = library.reduce<StoredStoryboard | undefined>(
    (latest, entry) => (!latest || entry.updatedAt > latest.updatedAt ? entry : latest),
    undefined
  );
  return structuredClone(recent?.project ?? fallback);
}

/** Validate the entire existing library before a single atomic localStorage write. */
export function saveStoryboard(
  storage: Pick<Storage, 'getItem' | 'setItem'>,
  project: Project,
  now = Date.now()
): StoredStoryboard[] {
  const entries = loadLibrary(storage) ?? [];
  const next: StoredStoryboard = {
    project: projectSchema.parse(structuredClone(project)),
    updatedAt: timestampSchema.parse(now),
  };
  const index = entries.findIndex((entry) => entry.project.id === next.project.id);
  if (index >= 0 && entries[index].deletedAt !== undefined)
    throw new Error('This storyboard is deleted. Restore it before saving.');
  if (index < 0) entries.push(next);
  else entries[index] = next;
  writeLibrary(storage, entries, 'save');
  return structuredClone(entries.filter((entry) => entry.deletedAt === undefined));
}

function writeLibrary(
  storage: Pick<Storage, 'setItem'>,
  entries: StoredStoryboard[],
  operation: 'save' | 'delete' | 'restore'
): void {
  try {
    const encoded = JSON.stringify(entries);
    storage.setItem(STORYBOARDS_STORAGE_KEY, encoded);
  } catch (cause) {
    throw new Error(
      `Could not ${operation} the storyboard. The existing library was left unchanged.`,
      { cause }
    );
  }
}

/** Move a document to the recoverable archive without changing its content. */
export function deleteStoryboard(
  storage: Pick<Storage, 'getItem' | 'setItem'>,
  id: string,
  now = Date.now()
): StoredStoryboard[] {
  const entries = loadLibrary(storage) ?? [];
  const entry = entries.find((item) => item.project.id === id);
  if (entry && entry.deletedAt === undefined) {
    entry.deletedAt = timestampSchema.parse(now);
    writeLibrary(storage, entries, 'delete');
  }
  return structuredClone(entries.filter((item) => item.deletedAt === undefined));
}

/** Restore the exact saved document, including its original revision and timestamp. */
export function restoreStoryboard(
  storage: Pick<Storage, 'getItem' | 'setItem'>,
  id: string
): StoredStoryboard[] {
  const entries = loadLibrary(storage) ?? [];
  const entry = entries.find((item) => item.project.id === id);
  if (entry && entry.deletedAt !== undefined) {
    delete entry.deletedAt;
    writeLibrary(storage, entries, 'restore');
  }
  return structuredClone(entries.filter((item) => item.deletedAt === undefined));
}

/** A small editable creative document; no hardware identity or aircraft state. */
export function createStoryboard(
  name = 'Untitled storyboard',
  id: string = crypto.randomUUID()
): Project {
  return projectSchema.parse({
    version: 1,
    id,
    revision: 0,
    name,
    droneCount: 1,
    bpm: 120,
    limits: {
      minimumSeparation: 2,
      maxSpeed: 8,
      maxAcceleration: 4,
      maxAltitude: 120,
      radius: 160,
    },
    cues: [
      {
        id: 'scene-1',
        name: 'Scene 1',
        shape: 'custom',
        palette: 'moonlight',
        duration: 10,
        transition: 0,
        scale: 1,
        altitude: 0,
        droneEdits: { '1': { position: [0, 0, 0] } },
      },
    ],
  });
}
